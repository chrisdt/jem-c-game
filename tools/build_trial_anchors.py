"""Measure the original atlas alpha without modifying any artwork."""
from pathlib import Path
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parents[1]
alpha = np.array(Image.open(root / 'assets/trial/miner_jab.png').getchannel('A'))
rows = [(0, 345), (345, 316), (661, 363)]
anchors = []
scales = []
for top, height in rows:
    row = []
    for col in range(4):
        mask = alpha[top:top+height, col*384:(col+1)*384] > 150
        yy, xx = np.nonzero(mask)
        bottom = int(yy.max()) + 1
        feet = np.nonzero(mask[max(0, bottom-20):bottom])[1]
        row.append((round(float(np.mean(feet)), 2), bottom))
        if col == 0:
            scales.append(round(84.0 / (bottom-int(yy.min())), 6))
    anchors.append(row)
text = '# Generated by tools/build_trial_anchors.py; source PNGs remain unchanged.\n'
text += 'extends RefCounted\nconst JAB_ANCHORS := [\n'
for row in anchors:
    text += '\t[' + ','.join(f'Vector2({x},{y})' for x,y in row) + '],\n'
text += ']\nconst JAB_SCALES := ' + str(scales) + '\n'
(root / 'assets/trial/anchors.gd').write_text(text)
print(text)
