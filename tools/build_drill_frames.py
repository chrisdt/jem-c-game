"""Analyze sprite alpha and write Godot atlas/boot anchors; never edit the art.

Optional authoring tool: Python with Pillow, NumPy and SciPy. Run from anywhere
after replacing drill sheets. Godot uses the checked-in resources directly.
"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
DIRECTIONS = ("down", "side", "up")
metadata = ["# Generated by tools/build_drill_frames.py; boot anchors in cropped source pixels.", "extends RefCounted", ""]

for outfit in ("miner", "scout"):
    for action, columns in (("walk", 4), ("mining", 3)):
        source = ROOT / "assets/drill" / f"{outfit}_{action}.png"
        alpha = np.asarray(Image.open(source).convert("RGBA"))[:, :, 3]
        labels, _ = ndimage.label(alpha > 32)
        areas = np.bincount(labels.ravel())
        objects = ndimage.find_objects(labels)
        figures = []
        for index, bounds in enumerate(objects, 1):
            if areas[index] > 2000:
                y, x = bounds
                figures.append((x.start, y.start, x.stop - x.start, y.stop - y.start))
        assert len(figures) == columns * 3, (source.name, figures)
        figures.sort(key=lambda box: box[1] + box[3] / 2)
        regions = []
        anchors = {}
        scales = {}
        for row, direction in enumerate(DIRECTIONS):
            band = sorted(figures[row * columns:(row + 1) * columns])
            scales[direction] = 80 / max(box[3] for box in band)
            anchors[direction] = []
            for col, box in enumerate(band):
                x, y, width, height = box
                # Keep the torso steady as alternate boots lift off the floor.
                # Anchoring to only the lowest boot makes a walk slide sideways.
                if action == "walk":
                    anchor_pixels = alpha[y:y + int(height * .28), x:x + width] > 96
                else:
                    anchor_pixels = alpha[y + int(height * .78):y + height, x:x + width] > 96
                foot_x = float(np.nonzero(anchor_pixels)[1].mean())
                anchors[direction].append((round(foot_x, 3), height))
                regions.append((direction, col, box))
        lines = [
            '[gd_resource type="SpriteFrames" load_steps=%d format=3]' % (len(regions) + 2),
            '',
            '[ext_resource type="Texture2D" path="res://assets/drill/%s_%s.png" id="1"]' % (outfit, action),
            '',
        ]
        for direction, col, box in regions:
            lines += [
                '[sub_resource type="AtlasTexture" id="%s_%d"]' % (direction, col),
                'atlas = ExtResource("1")',
                'region = Rect2(%s)' % ', '.join(map(str, box)),
                'filter_clip = true', '',
            ]
        animations = []
        for direction in DIRECTIONS:
            frames = ['{"duration": 1.0, "texture": SubResource("%s_%d")}' % (direction, i) for i in range(columns)]
            prefix = "walk" if action == "walk" else "mine"
            animations.append('{"frames": [%s], "loop": true, "name": &"%s_%s", "speed": 8.0}' % (', '.join(frames), prefix, direction))
            if action == "walk":
                animations.append('{"frames": [%s], "loop": true, "name": &"idle_%s", "speed": 8.0}' % (frames[1], direction))
        lines += ['[resource]', 'animations = [%s]' % ',\n'.join(animations), '']
        source.with_suffix('.tres').write_text('\n'.join(lines))
        key = f"{outfit}_{action}".upper()
        metadata.append(f"const {key}_ANCHORS := {{")
        for direction in DIRECTIONS:
            points = ', '.join('Vector2(%s, %s)' % point for point in anchors[direction])
            metadata.append('\t&"%s": [%s],' % (direction, points))
        metadata += ['}', f'const {key}_SCALES := {{']
        for direction in DIRECTIONS:
            metadata.append('\t&"%s": %.9f,' % (direction, scales[direction]))
        metadata += ['}', '']
        print(source.name, len(figures), 'complete poses')

(ROOT / 'assets/drill/anchors.gd').write_text('\n'.join(metadata))
